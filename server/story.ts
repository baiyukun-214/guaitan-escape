export function offlineFacts(text: string): string[] {
  // Deliberately conservative local keyword exercise, not semantic AI.
  const clauses = text
    .split(/[。；;！!\n]/)
    .filter((s) => !/(并非|不是|没有|未曾|不曾|不要|否认)/.test(s));
  return FACTS.filter((f) =>
    clauses.some((s) => f.patterns.every((p) => p.test(s))),
  ).map((f) => f.id);
}
